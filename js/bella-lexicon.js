//
// Reading the notation: the mark ˈ comes just before a stressed vowel, and ˌ before
// a lightly stressed one. Capital letters are gliding vowels: A as in "hey", I as in
// "high", O as in "oh", W as in "how", Y as in "soy". ɾ is the soft American t of
// "butter", ᵊ the faint vowel in "level", and ᵻ the light vowel of "added".
//
